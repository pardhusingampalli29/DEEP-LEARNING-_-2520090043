def measure_inference(device_name):

    current_device = torch.device(device_name)

    test_model = SimpleCNN().to(current_device)
    test_model.eval()

    sample = torch.randn(32, 3, 64, 64).to(current_device)

    with torch.inference_mode():

        for i in range(10):
            test_model(sample)

        if current_device.type == "cuda":
            torch.cuda.synchronize()

        start = time.time()

        for i in range(100):
            test_model(sample)

        if current_device.type == "cuda":
            torch.cuda.synchronize()

        end = time.time()

    return (end - start) / 100 * 1000


cpu_time = measure_inference("cpu")

print("CPU Inference Time:", cpu_time, "ms")

if torch.cuda.is_available():

    gpu_time = measure_inference("cuda")

    print("GPU Inference Time:", gpu_time, "ms")

