import torch
import time
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from ultralytics import YOLO
from glob import glob

print("PyTorch:", torch.__version__)
print("CUDA Available:", torch.cuda.is_available())

if torch.cuda.is_available():
    print("GPU:", torch.cuda.get_device_name(0))
else:
    print("Enable GPU in Runtime settings!")

model = YOLO("yolov8n.pt")

device = 0 if torch.cuda.is_available() else "cpu"

model.to(device)

print("YOLO Model Loaded Successfully!")
print("Model:", "YOLOv8n")
print("Device:", device)

from ultralytics.utils.downloads import download

download(
    "https://ultralytics.com/assets/coco128.zip",
    dir="/content/datasets",
    unzip=True
)

dataset_path = "/content/datasets/coco128/images/train2017"

image_paths = sorted(glob(dataset_path + "/*.jpg"))

print("Total Images:", len(image_paths))
print("Sample Images:", image_paths[:5])

from PIL import Image

plt.figure(figsize=(12, 5))

for i in range(min(3, len(image_paths))):
    plt.subplot(1, 3, i + 1)
    img = Image.open(image_paths[i])
    plt.imshow(img)
    plt.title(f"Image {i+1}")
    plt.axis("off")

plt.tight_layout()
plt.show()

model.model.eval()

# Warm-up runs
for i in range(5):
    model.predict(
        source=image_paths[0],
        imgsz=640,
        device=device,
        verbose=False
    )

if torch.cuda.is_available():
    torch.cuda.synchronize()

print("Model Evaluation Mode:", not model.model.training)
print("Warm-up Completed Successfully!")

latencies = []

for i in range(30):

    if torch.cuda.is_available():
        torch.cuda.synchronize()

    start = time.perf_counter()

    results = model.predict(
        source=image_paths[i % len(image_paths)],
        imgsz=640,
        device=device,
        verbose=False
    )

    if torch.cuda.is_available():
        torch.cuda.synchronize()

    end = time.perf_counter()

    latency = (end - start) * 1000
    latencies.append(latency)

avg_latency = np.mean(latencies)

print("Average Latency:", round(avg_latency, 3), "ms")
print("Minimum Latency:", round(min(latencies), 3), "ms")
print("Maximum Latency:", round(max(latencies), 3), "ms")

batch_size = 8

batch_images = image_paths[:batch_size]

if torch.cuda.is_available():
    torch.cuda.synchronize()

start = time.perf_counter()

batch_results = model.predict(
    source=batch_images,
    imgsz=640,
    device=device,
    verbose=False
)

if torch.cuda.is_available():
    torch.cuda.synchronize()

end = time.perf_counter()

total_batch_time = end - start

throughput = len(batch_images) / total_batch_time

print("Batch Size:", batch_size)
print("Images Processed:", len(batch_results))
print("Total Batch Time:", round(total_batch_time, 3), "seconds")
print("Throughput:", round(throughput, 3), "images/second")

if torch.cuda.is_available():

    torch.cuda.reset_peak_memory_stats()

    _ = model.predict(
        source=batch_images,
        imgsz=640,
        device=0,
        verbose=False
    )

    torch.cuda.synchronize()

    allocated = torch.cuda.memory_allocated() / (1024 ** 2)
    reserved = torch.cuda.memory_reserved() / (1024 ** 2)
    peak_memory = torch.cuda.max_memory_allocated() / (1024 ** 2)

    print("Allocated GPU Memory:", round(allocated, 2), "MB")
    print("Reserved GPU Memory:", round(reserved, 2), "MB")
    print("Peak GPU Memory:", round(peak_memory, 2), "MB")

else:
    allocated = reserved = peak_memory = 0
    print("GPU memory measurement unavailable.")

metrics = model.val(
    data="coco128.yaml",
    imgsz=640,
    batch=8,
    device=device,
    split="val",
    verbose=False
)

map50 = metrics.box.map50
map5095 = metrics.box.map

print("mAP@0.5:", round(map50, 4))
print("mAP@0.5:0.95:", round(map5095, 4))

report = {
    "Metric": [
        "mAP@0.5",
        "mAP@0.5:0.95",
        "Average Latency (ms)",
        "Minimum Latency (ms)",
        "Maximum Latency (ms)",
        "Throughput (images/sec)",
        "Allocated GPU Memory (MB)",
        "Peak GPU Memory (MB)"
    ],

    "Value": [
        map50,
        map5095,
        avg_latency,
        min(latencies),
        max(latencies),
        throughput,
        allocated,
        peak_memory
    ]
}

df = pd.DataFrame(report)

print("===== INFERENCE BASELINE REPORT =====")
display(df.round(3))

plt.figure(figsize=(10, 5))

plt.plot(
    range(1, len(latencies) + 1),
    latencies,
    marker="o"
)

plt.title("Inference Latency Measurement")
plt.xlabel("Inference Run")
plt.ylabel("Latency (ms)")
plt.grid(True)

plt.show()

plt.figure(figsize=(8, 5))

plt.bar(
    ["mAP@0.5", "mAP@0.5:0.95"],
    [map50, map5095]
)

plt.title("Object Detection Accuracy")
plt.ylabel("mAP Score")
plt.show()

df.to_csv(
    "Skill_9_Inference_Baseline_Report.csv",
    index=False
)

print("Report saved successfully!")

